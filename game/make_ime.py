"""Pinyin IME dictionary for the in-game keyboard -> game/build/ime_dict.lua

    python game/make_ime.py

Corpus = what players type to Paimon (the synthesized player turns) + general questions.
Characters: the most frequent ~4000 CJK characters with every reading (heteronyms).
Words: 2–4 character strings that occur often in the corpus and are real words
(pypinyin's phrase table, or a multi-character token of the model's tokenizer), plus
Genshin names. Ranked by corpus frequency. Output: a flat Lua array {py, word, freq, ...}.
"""
import collections, glob, json, os, re, sys
from pypinyin import lazy_pinyin, pinyin, Style
from pypinyin.phrases_dict import phrases_dict

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "distill"))
from gen_facts import ENTITIES
FLAG_RE = re.compile("fuck|shit|porn|sex|rape|nazi|dick|cunt|bitch|nigg|slut|whore|pussy|cock|kill|drug", re.I)   # = export_lua.FLAG_WORDS

OUT = os.path.join(os.path.dirname(__file__), "build", "ime_dict.lua")
CJK = re.compile(r"[一-鿿]+")
N_CHARS, MIN_WORD = 4000, 8

def corpus():
    texts = []
    D = "data/distill"
    for name in ["qa.jsonl", "multi.jsonl", "followup.jsonl", "facts.jsonl", "facts_world.jsonl"]:
        p = os.path.join(D, name)
        if not os.path.exists(p): continue
        for line in open(p, encoding="utf-8"):
            for x in json.loads(line)["items"]:
                texts.append(x["q"]); texts.append(x["a"])
    for p in glob.glob(os.path.join(D, "r*", "probe_q.jsonl")) + [os.path.join(D, "probe_q.jsonl")]:
        if os.path.exists(p):
            for line in open(p, encoding="utf-8"): texts += json.loads(line)["items"]
    with open("data/sft_t2t_mini.jsonl", encoding="utf-8") as f:       # general questions
        for i, line in enumerate(f):
            if i % 5: continue
            if i > 600000: break
            d = json.loads(line)["conversations"]
            texts.append(d[0]["content"][:200])
    return texts

def main():
    texts = corpus()
    chars, grams = collections.Counter(), collections.Counter()
    for t in texts:
        for run in CJK.findall(t):
            chars.update(run)
            for n in (2, 3, 4):
                for i in range(len(run) - n + 1): grams[run[i:i + n]] += 1
    vocab = set()
    tj = json.load(open("models/MiniMind2-Small/tokenizer.json", encoding="utf-8"))
    b2u = {}
    bs = list(range(33, 127)) + list(range(161, 173)) + list(range(174, 256)); cs = bs[:]; k = 0
    for b in range(256):
        if b not in bs: bs.append(b); cs.append(256 + k); k += 1
    u2b = {chr(c): b for b, c in zip(bs, cs)}
    for tok in tj["model"]["vocab"]:
        try: s = bytes(u2b[c] for c in tok).decode("utf-8")
        except Exception: continue
        if 2 <= len(s) <= 4 and CJK.fullmatch(s): vocab.add(s)
    names = set()
    for group in ENTITIES.values():
        for e in group:
            for part in re.split(r"[（）()/与和]", e):
                if 2 <= len(part) <= 6 and CJK.fullmatch(part): names.add(part)
    names |= {"派蒙", "旅行者", "应急食品", "摩拉", "原石", "宝箱", "甜甜花", "千星奇域", "奇域", "神之眼", "七天神像", "冒险家", "史莱姆", "丘丘人"}

    entries = []                                   # (pinyin, word, freq)
    for c, f in chars.most_common(N_CHARS):
        main = lazy_pinyin(c)[0]                       # the usual reading keeps the frequency,
        for py in dict.fromkeys(pinyin(c, style=Style.NORMAL, heteronym=True)[0]):
            if py.isalpha(): entries.append((py, c, f if py == main else max(1, f // 50)))   # rare readings sink
    words = 0
    for w, f in grams.most_common():
        if f < MIN_WORD: break
        if w in phrases_dict or w in vocab or w in names:
            py = "".join(lazy_pinyin(w))
            if py.isalpha(): entries.append((py, w, f)); words += 1
    for w in names:
        if not any(e[1] == w for e in entries):
            entries.append(("".join(lazy_pinyin(w)), w, max(MIN_WORD, grams[w])))
    entries.sort(key=lambda e: -e[2])
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by game/make_ime.py: flat {pinyin, word, frequency, ...}, most frequent first\nreturn {\n")
        # words as \ddd byte escapes: no plain Chinese text in the script (the level review scans it);
        # words of the filter's keyword list (game/filter_words.lua) are left out entirely
        blocked = set(re.findall(r"'([^']+)'", open(os.path.join(os.path.dirname(__file__), "filter_words.lua"), encoding="utf-8").read()))
        for py, w, fr in entries:
            if w in blocked: continue
            if FLAG_RE.search(py): py = "".join("\\%03d" % b for b in py.encode())   # e.g. "shitou"
            f.write('"%s","%s",%d,\n' % (py, "".join("\\%03d" % b for b in w.encode("utf-8")), fr))
        f.write("}\n")
    print(f"{len(texts)} texts; {N_CHARS} chars, {words} corpus words, {len(names)} names -> {len(entries)} entries, "
          f"{os.path.getsize(OUT)/1e3:.0f}KB")

if __name__ == "__main__":
    main()
