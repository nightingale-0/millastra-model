"""Lore lookup table for the in-game retrieval -> game/build/lore.lua

    python game/make_lore.py

From data/distill/lore_rag.jsonl (distill/gen_lore_rag.py): each entry's "名字：snippet" is one base85
string, decoded only when a question names it; names and aliases are stored as hashes of their
normalized UTF-8 bytes (same double hash as the filter keywords, game/chat.lua kwKey) -> entry index.
Names that are ordinary words in players' questions (general chat data) are not triggers, nor are the
chronicle section titles of the wiki (events, not things a player asks about by name).
"""
import collections, json, os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "export"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "embed"))
from export_lua import enc85
from train_filter import kw_hash
from train_encoder import norm_text

SRC = "data/distill/lore_rag.jsonl"
OUT = os.path.join(os.path.dirname(__file__), "build", "lore.lua")
ENTRIES = "data/lore/entries.jsonl"
COMMON_MAX = 20          # a name seen more often than this in general questions is an ordinary word

def lookup_keys(rows, where, common=lambda k: False, skipped=None):
    """[(entry text "名字：snippet", normalized trigger keys)], names before aliases. An alias is dropped
    when it is another entry's name or part of the entry's location ("挪德卡莱" for 希汐岛); regions get
    no aliases ("大枫丹湖" for 枫丹 is a lake in it)."""
    skipped = skipped if skipped is not None else collections.Counter()
    kinds = {json.loads(l)["name"]: json.loads(l)["kind"] for l in open(ENTRIES, encoding="utf-8")}
    rows = [r for r in rows if not (where.get(r["name"]) or "").startswith("提瓦特编年史") or skipped.update(["chronicle"])]
    own = {norm_text(r["name"].strip("「」")) for r in rows}
    out, taken = [], set()
    for r in rows:
        name = r["name"].strip("「」")
        names = {name}
        for n in ([] if kinds.get(r["name"]) == "地区" else r["aliases"]):
            k = norm_text(n)
            if k in own or (k and k in norm_text(where.get(r["name"]) or "")): skipped["bad alias"] += 1; continue
            names.add(n)
        for n in list(names):
            parts = re.split(r"[·・]", n)
            if len(parts) > 1 and len(parts[-1]) >= 3: names.add(parts[-1])
        keys = []
        for n in sorted(names, key=lambda n: n != name):          # the entry's own name first
            k = norm_text(n)
            if len(k) < 2 or len(k) > 10 or k in taken: continue
            if k != norm_text(name) and k in own: continue
            if common(k): skipped["common: " + k] += 1; continue
            keys.append(k)
        if not keys: continue
        taken |= set(keys)
        out.append((f"{name}：{r['snippet']}", keys))
    return out

def main():
    where = {json.loads(l)["name"]: json.loads(l)["where"] for l in open(ENTRIES, encoding="utf-8")}
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
    qs = collections.Counter()
    with open("data/sft_t2t_mini.jsonl", encoding="utf-8") as f:
        for i, l in enumerate(f):
            if i % 4: continue
            if i > 400000: break
            qs[norm_text(json.loads(l)["conversations"][0]["content"])] += 1
    general = list(qs)
    def common(n):
        return sum(1 for q in general if n in q) > COMMON_MAX
    entries, index, skipped = [], {}, collections.Counter()
    for text, keys in lookup_keys(rows, where, common, skipped):
        entries.append(text)
        for k in keys: index.setdefault(kw_hash(k), len(entries))
    kmax = max(len(norm_text(e.split("：")[0])) for e in entries)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by game/make_lore.py: retrieval snippets (base85, decoded on a hit) + name hashes\nreturn {\n")
        f.write(f"kmax={min(kmax, 10)},\nidx={{" + ",".join(f"[{h}]={i}" for h, i in sorted(index.items())) + "},\n")
        # entry = {byte length, base85 text}: decoded only when its name is asked about
        f.write("e={\n" + ",\n".join("{%d,[==[%s]==]}" % (len(e.encode("utf-8")), "".join(enc85(e.encode("utf-8")))) for e in entries) + "},\n}\n")
    print(f"{len(entries)} entries, {len(index)} name keys, kmax {kmax}; skipped {dict(skipped.most_common(8))}; "
          f"{os.path.getsize(OUT) / 1e3:.0f}KB -> {OUT}")

if __name__ == "__main__":
    main()
